#!/usr/bin/env python3
"""Generate DTOs from the committed OpenAPI contract."""
import json
import argparse
from pathlib import Path
root=Path(__file__).resolve().parents[2]
schemas=json.loads((root/'openapi/spindle.json').read_text())['components']['schemas']
def kotlin(p):
 nullable=isinstance(p.get('type'),list) and 'null' in p['type']
 if 'oneOf' in p:
  nullable=any(v.get('type')=='null' for v in p['oneOf']);p=next((v for v in p['oneOf'] if v.get('type')!='null'),{})
 if '$ref' in p:t=p['$ref'].split('/')[-1]
 else:
  typ=p.get('type','object');typ=next((v for v in typ if v!='null'),'object') if isinstance(typ,list) else typ
  t={'string':'String','boolean':'Boolean','integer':'Long' if p.get('format')=='int64' else 'Int','number':'Double','object':'JsonObject'}.get(typ)
  if typ=='array':t='List<'+kotlin(p['items'])[0]+'>'
  t=t or 'JsonElement'
 return t+('?' if nullable else ''),nullable
lines=['// Generated by android/scripts/generate-models.py.','package com.spindletrack.android.data','','import kotlinx.serialization.Serializable','import kotlinx.serialization.json.JsonElement','import kotlinx.serialization.json.JsonObject','']
for name,s in schemas.items():
 if s.get('type')!='object':lines += [f'typealias {name} = String',''];continue
 props=list(s.get('properties',{}).items())
 if not props:lines+=['@Serializable',f'class {name}',''];continue
 lines+=['@Serializable',f'data class {name}(']
 for prop,p in props:
  t,n=kotlin(p)
  d='null' if n else ('emptyList()' if t.startswith('List<') else {'String':'""','Int':'0','Long':'0L','Double':'0.0','Boolean':'false','JsonObject':'JsonObject(emptyMap())','JsonElement':'JsonObject(emptyMap())'}.get(t,'""' if schemas.get(t,{}).get('type')!='object' else f'{t}()'))
  lines += [f'    val `{prop}`: {t} = {d},']
 lines+=[')','']
output=root/'android/app/src/main/java/com/spindletrack/android/data/Models.kt'
content='\n'.join(lines)
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true',help='Fail if committed models differ from OpenAPI')
args=parser.parse_args()
if args.check:
 if not output.exists() or output.read_text()!=content:
  parser.exit(1,'Android API models are stale. Run python3 android/scripts/generate-models.py.\n')
else:
 output.write_text(content)
