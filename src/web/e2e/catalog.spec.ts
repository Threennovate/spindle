import { expect, test } from '@playwright/test'
import { registerNewUser } from './support.ts'

test('a project with a new client, a task, then archived and deleted', async ({ page }) => {
  await registerNewUser(page)
  await page.getByRole('link', { name: 'Projects' }).click()
  await expect(page.getByText('No projects yet')).toBeVisible()

  await page.getByRole('button', { name: 'New project' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Name').fill('Rebrand')
  await dialog.getByRole('button', { name: 'New client' }).click()
  await dialog.getByLabel('New client name').fill('Acme')
  await dialog.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(dialog.getByRole('combobox', { name: 'Client' })).toHaveText('Acme')
  await dialog.getByLabel('Estimate (hours)').fill('12.5')
  await dialog.getByLabel('Billable').click()
  await dialog.getByRole('button', { name: 'Create project' }).click()

  const row = page.getByRole('row').filter({ hasText: 'Rebrand' })
  await expect(row).toContainText('Acme')
  await expect(row).toContainText('0m')

  await row.getByRole('link', { name: /Rebrand/ }).click()
  await expect(page.getByRole('heading', { name: 'Rebrand' })).toBeVisible()
  await expect(page.getByText('Billable')).toBeVisible()
  await page.getByLabel('New task name').fill('Logo')
  await page.getByRole('button', { name: 'Add task' }).click()
  await page.getByRole('checkbox', { name: 'Mark Logo done' }).click()
  await expect(page.getByRole('checkbox', { name: 'Reopen Logo' })).toBeChecked()

  await page.getByRole('link', { name: 'Projects' }).first().click()
  await row.getByRole('button', { name: 'Actions for Rebrand' }).click()
  await page.getByRole('menuitem', { name: 'Archive' }).click()
  await expect(row).toHaveCount(0)
  await page.getByRole('tab', { name: 'Archived' }).click()
  await expect(row).toContainText('Archived')

  await row.getByRole('button', { name: 'Actions for Rebrand' }).click()
  await page.getByRole('menuitem', { name: 'Delete' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete project' }).click()
  await expect(row).toHaveCount(0)
})

test('clients and tags can be added, renamed and removed', async ({ page }) => {
  await registerNewUser(page)

  await page.getByRole('link', { name: 'Clients' }).click()
  await page.getByLabel('New client name').fill('Globex')
  await page.getByRole('button', { name: 'Add client' }).click()
  await expect(page.getByRole('button', { name: 'Actions for Globex' })).toBeVisible()
  await page.getByLabel('New client name').fill('globex')
  await page.getByRole('button', { name: 'Add client' }).click()
  await expect(page.getByText('A client with this name already exists.')).toBeVisible()
  await page.getByRole('button', { name: 'Actions for Globex' }).click()
  await page.getByRole('menuitem', { name: 'Rename' }).click()
  await page.getByLabel('Client name', { exact: true }).fill('Globex Corp')
  await page.getByRole('button', { name: 'Save' }).click()
  await page.getByRole('button', { name: 'Actions for Globex Corp' }).click()
  await page.getByRole('menuitem', { name: 'Archive' }).click()
  await expect(page.getByText('No clients yet')).toBeVisible()
  await page.getByRole('tab', { name: 'Archived' }).click()
  await page.getByRole('button', { name: 'Actions for Globex Corp' }).click()
  await page.getByRole('menuitem', { name: 'Delete' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete client' }).click()
  await expect(page.getByText('No archived clients.')).toBeVisible()

  await page.getByRole('link', { name: 'Tags' }).click()
  await page.getByLabel('New tag name').fill('meeting')
  await page.getByRole('button', { name: 'Add tag' }).click()
  await expect(page.getByLabel('New tag name')).toHaveValue('')
  await page.getByRole('button', { name: 'Actions for meeting' }).click()
  await page.getByRole('menuitem', { name: 'Rename' }).click()
  await page.getByLabel('Tag name', { exact: true }).fill('meetings')
  await page.getByRole('button', { name: 'Save' }).click()
  await page.getByRole('button', { name: 'Actions for meetings' }).click()
  await page.getByRole('menuitem', { name: 'Delete' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete tag' }).click()
  await expect(page.getByText('No tags yet')).toBeVisible()
})
