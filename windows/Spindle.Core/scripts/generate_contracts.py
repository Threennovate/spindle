"""Generate the Windows client's supported API contracts from the checked-in OpenAPI."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[3]
schemas = json.loads((root / 'openapi/spindle.json').read_text())['components']['schemas']
names = set('MemberResponse GroupResponse ProjectMemberResponse ProjectMemberRequest ChangePasswordRequest RepositoryLinkRequest RepositoryLinkResponse AgentActivitySettingsRequest AuthTokensResponse ExternalExchangeRequest ExternalSignInResponse LoginRequestRegisterRequest RefreshRequest ProfileRequest PreferencesRequest MeResponse WorkspaceSummary TimeEntryRequest CreateTimeEntryRequest TimeEntryResponse StopTimeEntryRequest BulkUpdateTimeEntriesRequest BulkDeleteTimeEntriesRequest TimeEntrySuggestion SplitSuggestionResponse ProjectRequest ProjectResponse TaskRequest TaskResponse ClientRequest ClientResponse TagRequest TagResponse WorkspaceSettingsResponse SummaryReportRequest SummaryReport DetailedReportRequest DetailedReport WeeklyReportRequest WeeklyReport'.split())
def refs(value):
    if isinstance(value, dict):
        if '$ref' in value: yield value['$ref'].split('/')[-1]
        for v in value.values(): yield from refs(v)
    elif isinstance(value,list):
        for v in value: yield from refs(v)
while True:
    expanded = names | {r for n in names for r in refs(schemas[n])}
    if expanded == names: break
    names = expanded

def kind(s):
    if 'oneOf' in s:
        inner = next(v for v in s['oneOf'] if v.get('type') != 'null')
        return kind(inner).rstrip('?')+'?'
    if '$ref' in s: return s['$ref'].split('/')[-1]
    t = s.get('type','object'); nullable = isinstance(t,list) and 'null' in t
    if isinstance(t,list): t=next(v for v in t if v!='null')
    typ={'string': {'uuid':'Guid','date-time':'DateTimeOffset','date':'DateOnly'}.get(s.get('format'),'string'), 'integer': 'long' if s.get('format')=='int64' else 'int','number':'decimal','boolean':'bool','array': 'ARRAY','object':'System.Text.Json.JsonElement'}[t]
    if t == 'array': typ=kind(s.get('items',{}))+'[]'
    return typ+('?' if nullable else '')
lines=['// Generated by scripts/generate_contracts.py from openapi/spindle.json.','using System.Text.Json.Serialization;','namespace Spindle.Core;','']
for n in sorted(names):
    s=schemas[n]
    if 'enum' in s:
        lines += [f'public enum {n} {{ '+', '.join(v[0].upper()+v[1:] for v in s['enum'])+' }','']
        continue
    lines += [f'public sealed record {n}','{']
    for p,v in s.get('properties',{}).items():
        typ=kind(v); default=''
        if typ=='string': default=' = "";'
        elif typ.endswith('[]'): default=' = [];'
        elif typ in names and 'enum' not in schemas[typ]: default=' = new();'
        if p=='roundingMinutes': default=' = 15;'
        if n=='DetailedReportRequest' and p=='page': default=' = 1;'
        if n=='DetailedReportRequest' and p=='pageSize': default=' = 50;'
        if n=='SummaryReportRequest' and p=='subGroupBy': default=' = ReportGrouping.Description;'
        if n=='DetailedReportRequest' and p=='descending': default=' = true;'
        lines += [f'    public {typ} {p[0].upper()+p[1:]} {{ get; init; }}{default}']
    lines += ['}','']
(root/'windows/Spindle.Core/Contracts.cs').write_text('\n'.join(lines))
