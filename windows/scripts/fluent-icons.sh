#!/usr/bin/env bash
# Regenerates windows/Spindle.Windows/Theme/Icons.axaml from Fluent UI System Icons (MIT, Microsoft).
# Add an icon by putting its file name (without .svg) in ICONS, then run this script from the repository root.
set -euo pipefail
VERSION=1.1.344
ICONS="add_20_regular alert_20_regular archive_20_regular arrow_clockwise_20_regular arrow_download_20_regular
arrow_left_20_regular arrow_split_20_regular arrow_sync_20_regular arrow_undo_20_regular bot_20_regular branch_20_regular
building_multiple_20_regular calendar_day_20_regular calendar_ltr_20_regular calendar_week_start_20_regular
checkmark_20_regular checkmark_circle_20_filled chevron_down_20_regular chevron_left_20_regular chevron_right_20_regular
chevron_up_down_20_regular clock_20_regular cloud_off_20_regular copy_20_regular currency_dollar_euro_20_regular
data_bar_vertical_20_regular delete_20_regular desktop_20_regular dismiss_16_regular dismiss_20_regular
drink_coffee_20_regular edit_20_regular error_circle_20_filled eye_20_regular eye_off_20_regular filter_20_regular folder_20_regular
folder_add_20_regular info_20_filled keyboard_20_regular link_20_regular lock_closed_16_filled lock_closed_20_regular
money_20_regular more_horizontal_20_regular open_20_regular people_20_regular person_20_regular person_circle_20_regular
pin_20_regular play_20_filled play_20_regular play_circle_20_regular plug_connected_20_regular power_20_regular
search_20_regular server_20_regular settings_20_regular shield_20_regular sign_out_20_regular sparkle_20_filled
sparkle_20_regular stop_20_filled stop_20_regular tag_20_regular tag_multiple_20_regular target_20_regular
text_bullet_list_add_20_regular timer_20_regular warning_20_filled wifi_off_20_regular window_20_regular"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
for name in $ICONS; do
  curl -sfL "https://unpkg.com/@fluentui/svg-icons@$VERSION/icons/$name.svg" -o "$WORK/$name.svg"
done
python3 -I - "$WORK" windows/Spindle.Windows/Theme/Icons.axaml <<'PY'
import glob, os, re, sys
source, target = sys.argv[1], sys.argv[2]
def key(path):
    base = os.path.basename(path)[:-4]
    words, size, style = re.match(r'(.*)_(\d+)_(regular|filled)$', base).groups()
    name = ''.join(w.capitalize() for w in words.split('_'))
    return 'Icon' + name + ('' if size == '20' else size) + ('Filled' if style == 'filled' else '')
lines = ['<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
         '  <!-- Fluent UI System Icons, MIT License, Copyright (c) 2020 Microsoft Corporation. 20×20 unless the name says otherwise. -->',
         '  <!-- Generated by windows/scripts/fluent-icons.sh. -->']
for path in sorted(glob.glob(source + '/*.svg')):
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', open(path).read())
    lines.append(f'  <StreamGeometry x:Key="{key(path)}">{" ".join(paths)}</StreamGeometry>')
lines.append('</ResourceDictionary>')
open(target, 'w').write('\n'.join(lines) + '\n')
PY
